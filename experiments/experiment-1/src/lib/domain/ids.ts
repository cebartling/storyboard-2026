/**
 * Branded id types for each entity in the StoryMap aggregate (see
 * documentation/domain-model.md). Branding prevents accidentally passing, say,
 * a StepId where an ActivityId is expected — both are plain strings at
 * runtime, but the type checker keeps them apart.
 */

declare const brand: unique symbol;
type Brand<T, B extends string> = T & { readonly [brand]: B };

export type MapId = Brand<string, 'MapId'>;
export type ActivityId = Brand<string, 'ActivityId'>;
export type StepId = Brand<string, 'StepId'>;
export type SliceId = Brand<string, 'SliceId'>;
export type StoryId = Brand<string, 'StoryId'>;

/**
 * The person making a request (ADR 0016). Branded like the entity ids, which
 * is what stops ADR 0015 §6's presence client id — a different brand entirely —
 * from ever being passed where an authenticated identity is expected.
 */
export type UserId = Brand<string, 'UserId'>;

/**
 * One browser tab's connection to a map's event stream (ADR 0015 §6).
 *
 * Branded so that "which tab is this" cannot be passed where "who is this" is
 * expected. `UserId` being branded already stops a `ClientId` masquerading as
 * an identity; this makes the protection run both ways, which is what ADR 0016
 * §6 says it does.
 *
 * It lives here beside the entity ids for the brand, and nothing else: it is
 * never persisted, never in a cookie, and no domain function takes one.
 */
export type ClientId = Brand<string, 'ClientId'>;

/**
 * Generates a UUIDv7: a time-ordered UUID (RFC 9562) — sorting by id sorts by
 * creation time *to the millisecond*, which is convenient for debugging and
 * for any future "recently created" listing.
 *
 * Not monotonic within a millisecond: RFC 9562 leaves the sub-millisecond
 * counter optional and this does not implement one, so ids minted in the same
 * tick are ordered randomly relative to each other. The seed builder makes
 * ~215 of them in one tick. Nothing depends on their order today; anything
 * that comes to depend on it needs the counter, not just this comment. Node 24's `crypto.randomUUID()` only
 * produces v4 (no time ordering), and no v7 driver is otherwise part of this
 * project's toolchain, so it's generated by hand here: a 48-bit millisecond
 * timestamp followed by 74 random bits, with the version and variant bits
 * set per the spec.
 */
function uuidv7(): string {
	const bytes = crypto.getRandomValues(new Uint8Array(16));

	const now = BigInt(Date.now());
	bytes[0] = Number((now >> 40n) & 0xffn);
	bytes[1] = Number((now >> 32n) & 0xffn);
	bytes[2] = Number((now >> 24n) & 0xffn);
	bytes[3] = Number((now >> 16n) & 0xffn);
	bytes[4] = Number((now >> 8n) & 0xffn);
	bytes[5] = Number(now & 0xffn);

	// Version 7 in the top nibble of byte 6.
	bytes[6] = (bytes[6] & 0x0f) | 0x70;
	// Variant 10xxxxxx in the top two bits of byte 8.
	bytes[8] = (bytes[8] & 0x3f) | 0x80;

	const hex = Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('');
	return [
		hex.slice(0, 8),
		hex.slice(8, 12),
		hex.slice(12, 16),
		hex.slice(16, 20),
		hex.slice(20)
	].join('-');
}

/** Generates a new branded id of the requested kind. */
export function newId<T extends string>(): T {
	return uuidv7() as T;
}
